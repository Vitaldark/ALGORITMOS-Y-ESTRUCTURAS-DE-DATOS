import torch
import torch.nn as nn
import numpy as np
import matplotlib.pyplot as plt
import segmentation_models_pytorch as smp
from torch.utils.data import Dataset, DataLoader
import time, warnings
warnings.filterwarnings('ignore')

DEVICE = 'cuda' if torch.cuda.is_available() else 'cpu'
print(f"🖥  Dispositivo: {DEVICE}\n")

class MiningDataset(Dataset):
    def __init__(self, n_samples=200):
        self.n = n_samples
    def __len__(self):
        return self.n
    def __getitem__(self, idx):
        np.random.seed(idx)
        H, W = 128, 128
        img  = np.random.normal(0.08, 0.02, (4,H,W)).astype(np.float32)
        mask = np.zeros((H,W), dtype=np.float32)
        for _ in range(np.random.randint(1,4)):
            cx,cy = np.random.randint(20,W-20), np.random.randint(20,H-20)
            rx,ry = np.random.randint(8,25), np.random.randint(8,20)
            y,x   = np.ogrid[:H,:W]
            zona  = ((x-cx)/rx)**2 + ((y-cy)/ry)**2 <= 1
            img[0][zona] = np.random.normal(0.35, 0.05, zona.sum())
            img[3][zona] = np.random.normal(0.05, 0.02, zona.sum())
            mask[zona]   = 1.0
        return torch.tensor(img.clip(0,1)), torch.tensor(mask).unsqueeze(0)

def calc_iou(preds, masks):
    p = (preds > 0.5).float()
    intersection = (p * masks).sum()
    union = p.sum() + masks.sum() - intersection
    return (intersection / (union + 1e-8)).item()

print("🧠 Cargando U-Net + ResNet50...")
model = smp.Unet(
    encoder_name="resnet50",
    encoder_weights="imagenet",
    in_channels=4, classes=1, activation='sigmoid'
).to(DEVICE)
print(f"✅ {sum(p.numel() for p in model.parameters()):,} parámetros\n")

train_loader = DataLoader(MiningDataset(160), batch_size=8, shuffle=True)
val_loader   = DataLoader(MiningDataset(40),  batch_size=8, shuffle=False)

class CombinedLoss(nn.Module):
    def __init__(self):
        super().__init__()
        self.dice = smp.losses.DiceLoss(mode='binary')
        self.bce  = smp.losses.SoftBCEWithLogitsLoss()
    def forward(self, pred, target):
        return self.dice(pred, target) + self.bce(pred, target)

criterion = CombinedLoss()
optimizer = torch.optim.AdamW(model.parameters(), lr=1e-4, weight_decay=1e-5)
scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=10)

print("🚀 Entrenando U-Net — 10 épocas demo")
print(f"{'Época':<6} {'Loss Train':>11} {'mIoU Train':>11} {'Loss Val':>10} {'mIoU Val':>10} {'Tiempo':>8}")
print("─" * 62)

history = {'train_loss':[],'train_iou':[],'val_loss':[],'val_iou':[]}
best_iou = 0.0

for epoch in range(1, 11):
    t0 = time.time()

    model.train()
    tl, ti = 0, 0
    for imgs, masks in train_loader:
        imgs, masks = imgs.to(DEVICE), masks.to(DEVICE)
        optimizer.zero_grad()
        preds = model(imgs)
        loss  = criterion(preds, masks)
        loss.backward()
        optimizer.step()
        tl += loss.item()
        ti += calc_iou(preds, masks)
    tl /= len(train_loader)
    ti /= len(train_loader)

    model.eval()
    vl, vi = 0, 0
    with torch.no_grad():
        for imgs, masks in val_loader:
            imgs, masks = imgs.to(DEVICE), masks.to(DEVICE)
            preds = model(imgs)
            loss  = criterion(preds, masks)
            vl += loss.item()
            vi += calc_iou(preds, masks)
    vl /= len(val_loader)
    vi /= len(val_loader)

    scheduler.step()
    elapsed = time.time() - t0
    history['train_loss'].append(tl)
    history['train_iou'].append(ti)
    history['val_loss'].append(vl)
    history['val_iou'].append(vi)

    if vi > best_iou:
        best_iou = vi
        torch.save(model.state_dict(), 'unet_vigia_best.pth')
        flag = " ✅ mejor"
    else:
        flag = ""

    print(f"{epoch:<6} {tl:>11.4f} {ti:>11.4f} {vl:>10.4f} {vi:>10.4f} {elapsed:>6.1f}s{flag}")

