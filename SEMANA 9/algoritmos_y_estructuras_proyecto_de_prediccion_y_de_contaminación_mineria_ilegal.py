# Generar imagen sintética realista de minería vs bosque
# (mismas características espectrales que Sentinel-2 real)
np.random.seed(42)
H, W = 256, 256

# Banda NIR (B8) — bosque alto, minería bajo
nir  = np.random.normal(0.45, 0.06, (H,W)).clip(0,1)
# Banda Rojo (B4)
red  = np.random.normal(0.08, 0.02, (H,W)).clip(0,1)
# Banda Verde (B3)
grn  = np.random.normal(0.12, 0.02, (H,W)).clip(0,1)
# Banda Azul (B2)
blu  = np.random.normal(0.06, 0.01, (H,W)).clip(0,1)

# Insertar zonas de minería (firma espectral real: NIR bajo, Rojo alto)
def add_mining(img_nir, img_red, img_grn, img_blu, cx, cy, rx, ry, tipo):
    y, x = np.ogrid[:H, :W]
    mask = ((x-cx)/rx)**2 + ((y-cy)/ry)**2 <= 1
    if tipo == "poza":  # poza de sedimentos — azulada
        img_nir[mask]  = np.random.normal(0.04, 0.01, mask.sum()).clip(0,0.1)
        img_red[mask]  = np.random.normal(0.18, 0.03, mask.sum()).clip(0,0.3)
        img_grn[mask]  = np.random.normal(0.22, 0.03, mask.sum()).clip(0,0.35)
        img_blu[mask]  = np.random.normal(0.28, 0.04, mask.sum()).clip(0,0.4)
    elif tipo == "suelo":  # suelo removido — marrón
        img_nir[mask]  = np.random.normal(0.15, 0.03, mask.sum()).clip(0,0.25)
        img_red[mask]  = np.random.normal(0.35, 0.04, mask.sum()).clip(0,0.5)
        img_grn[mask]  = np.random.normal(0.28, 0.03, mask.sum()).clip(0,0.4)
        img_blu[mask]  = np.random.normal(0.20, 0.03, mask.sum()).clip(0,0.3)
    elif tipo == "rio":  # río/canal — oscuro
        img_nir[mask]  = np.random.normal(0.02, 0.005, mask.sum()).clip(0,0.05)
        img_red[mask]  = np.random.normal(0.04, 0.01,  mask.sum()).clip(0,0.08)
        img_grn[mask]  = np.random.normal(0.06, 0.01,  mask.sum()).clip(0,0.1)
        img_blu[mask]  = np.random.normal(0.08, 0.01,  mask.sum()).clip(0,0.12)

# Zonas de minería realistas (como La Pampa real)
add_mining(nir, red, grn, blu,  80, 100, 35, 22, "suelo")
add_mining(nir, red, grn, blu, 130,  85, 18, 12, "poza")
add_mining(nir, red, grn, blu, 160, 120, 25, 15, "suelo")
add_mining(nir, red, grn, blu, 105, 140, 15, 10, "poza")
add_mining(nir, red, grn, blu,  70, 160, 12,  8, "poza")
add_mining(nir, red, grn, blu, 200,  60, 10, 40, "rio")   # río

# Calcular NDVI: (NIR - Red) / (NIR + Red)
ndvi = (nir - red) / (nir + red + 1e-8)

# Calcular NDWI: (Green - NIR) / (Green + NIR) — detecta agua/pozas
ndwi = (grn - nir) / (grn + nir + 1e-8)

# Composición RGB natural
rgb = np.stack([red, grn, blu], axis=2)
rgb = (rgb - rgb.min()) / (rgb.max() - rgb.min())
rgb = np.power(rgb, 0.6)  # corrección gamma

# Composición falso color (NIR-R-G) — resalta vegetación en rojo
nrg = np.stack([nir, red, grn], axis=2)
nrg = (nrg - nrg.min()) / (nrg.max() - nrg.min())

# Máscara de minería detectada (NDVI bajo + no agua)
mining_mask = (ndvi < 0.15) & (ndwi < 0.1)

